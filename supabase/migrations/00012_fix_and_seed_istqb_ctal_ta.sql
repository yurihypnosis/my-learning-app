-- ===== 1. answer_events =====
CREATE TABLE IF NOT EXISTS public.answer_events (
  id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       UUID        NOT NULL,
  question_id   UUID        NOT NULL,
  category_id   UUID        NOT NULL,
  category_name TEXT        NOT NULL,
  category_color TEXT       NOT NULL DEFAULT '#64748b',
  subject_slug  TEXT        NOT NULL,
  is_correct    BOOLEAN     NOT NULL,
  confidence    INTEGER,
  answered_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.answer_events ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_policies WHERE tablename='answer_events' AND policyname='users can insert own answer events') THEN
    CREATE POLICY "users can insert own answer events" ON public.answer_events FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_policies WHERE tablename='answer_events' AND policyname='users can read own answer events') THEN
    CREATE POLICY "users can read own answer events" ON public.answer_events FOR SELECT TO authenticated USING (auth.uid() = user_id);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS answer_events_user_date_idx ON public.answer_events (user_id, answered_at DESC);

